"""Write the generated collections into the app: keys, compact rows, EN/AR names, artwork + thumbnails.
The first collection (gen.py: weddings, newborns, Ramadan) and the second (gen3.py: birthdays, baby showers,
graduation, henna, corporate, engagements, gatherings) are published together, in that order.
usage: emit.py <repo>"""
import json, os, shutil, sys
repo = sys.argv[1]
SOURCES = [("artdata/collection.json", "artdata/out2", "artdata/thumb2"), ("artdata/collection3.json", "artdata/out3", "artdata/thumb3")]
rows, art = [], {}
for coll, out, thumb in SOURCES:
    if not os.path.exists(coll): continue
    for r in json.load(open(coll)):
        rows.append(r); art[r["k"]] = (out, thumb)
assert len({r["k"] for r in rows}) == len(rows), "duplicate keys across collections"
T = os.path.join(repo, "src/lib/themes")
keys = [r["k"] for r in rows]
open(f"{T}/collection-keys.ts", "w").write(
    "// Generated by scripts/stationery — the keys of the generated artwork collection (see collection.ts).\n"
    "export const COLLECTION_KEYS = [\n" + "".join(f'  "{k}",\n' for k in keys) + "] as const;\n")

def js(v):
    return json.dumps(v, ensure_ascii=False)

occ_sets = {}
lines = []
for r in rows:
    o = js(r["o"])
    if o not in occ_sets: occ_sets[o] = f"O{len(occ_sets)}"
    parts = [f'k: "{r["k"]}"', f"o: {occ_sets[o]}"]
    if r.get("p"): parts.append("p: 1")
    if r.get("l"): parts.append(f'l: "{r["l"]}"')
    parts.append(f"c: {js(r['c'])}")
    parts.append(f"f: {js(r['f'])}")
    if r.get("n"): parts.append(f"n: {js(r['n'])}")
    if r.get("s"): parts.append(f"s: {r['s']}")
    if r.get("u"): parts.append("u: 1")
    parts.append(f"b: {js(r['b'])}")
    parts.append(f'd: "{r["d"]}"')
    parts.append(f'y: "{r["y"]}"')
    lines.append("  { " + ", ".join(parts) + " },")
consts = "".join(f"const {name}: EventType[] = {o};\n" for o, name in occ_sets.items())
open(f"{T}/collection-data.ts", "w").write(
    "// Generated by scripts/stationery — do not edit by hand.\n"
    'import type { EventType } from "@prisma/client";\n'
    'import type { CollectionRow } from "./collection";\n\n' + consts + "\n"
    "export const COLLECTION_ROWS: CollectionRow[] = [\n" + "\n".join(lines) + "\n];\n")

def names(lang):
    return "".join(f'    "{r["k"]}": {{ name: {js(r["names"][lang]["name"])}, description: {js(r["names"][lang]["description"])} }},\n' for r in rows)
open(f"{T}/collection-names.ts", "w").write(
    "// Generated by scripts/stationery — do not edit by hand.\n"
    'import type { CollectionKey } from "./types";\n\n'
    "type Names = Record<CollectionKey, { name: string; description: string }>;\n\n"
    "export const COLLECTION_NAMES: { en: Names; ar: Names } = {\n  en: {\n" + names("en") + "  },\n  ar: {\n" + names("ar") + "  },\n};\n")

pub = os.path.join(repo, "public/stationery"); os.makedirs(f"{pub}/thumb", exist_ok=True)
for k in keys:
    out, thumb = art[k]
    shutil.copyfile(f"{out}/{k}.jpg", f"{pub}/{k}.jpg")
    shutil.copyfile(f"{thumb}/{k}.jpg", f"{pub}/thumb/{k}.jpg")
# Drop artwork of designs no longer in the collection (keeps the hand-arranged 27).
keep = set(keys) | {"peony", "redoute", "whiterose", "crimson", "camellia", "cherry", "magnolia", "taif", "jasmine", "olive", "laurel", "wildflower", "tulip", "hydrangea", "sweetpea", "forgetmenot", "lilyvalley", "orchid", "lily", "iris", "wisteria", "poppy", "lavender", "pomegranate", "anemone", "daisy", "fern"}
for d in (pub, f"{pub}/thumb"):
    for f in os.listdir(d):
        if f.endswith(".jpg") and f[:-4] not in keep: os.remove(os.path.join(d, f))
print(len(keys), "designs emitted")
